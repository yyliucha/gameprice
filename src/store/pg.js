/**
 * 个人标记：null 表示"不设置/保持"，写入后该字段优先于全局标记。
 * 返回该游戏的最终生效值（个人优先，回退全局）。
 */
export async function setUserGameFlag(q, { userId, gameId, interested = null, owned = null }) {
  // 语义：boolean = 设置；null/undefined = 不改动；'clear' = 显式置空（回退全局 games 标记）
  const norm = (v) => (v === 'clear' ? null : typeof v === 'boolean' ? v : null);
  const upd = [];
  if (interested === 'clear') upd.push('interested = null');
  else if (typeof interested === 'boolean') upd.push('interested = $3');
  if (owned === 'clear') upd.push('owned = null');
  else if (typeof owned === 'boolean') upd.push('owned = $4');
  const set = upd.length ? `set ${upd.join(', ')}, updated_at = now()` : 'set updated_at = now()';
  await q(
    `insert into user_game_flags (user_id, game_id, interested, owned) values ($1, $2, $3, $4)
     on conflict (user_id, game_id) do update ${set}`,
    [userId, gameId, norm(interested), norm(owned)],
  );
  const r = await q(
    `select coalesce(uf.interested, g.interested) as interested, coalesce(uf.owned, g.owned) as owned
       from games g
       left join user_game_flags uf on uf.game_id = g.id and uf.user_id = $2
      where g.id = $1`,
    [gameId, userId],
  );
  return r.rows[0] ?? null;
}

/** 后台游戏同步概览：库内总数 / 有 appid / 待同步信息 / 已删除 / 有报价。 */
export async function adminGameStats(q) {
  const r = await q(`
    select count(*)::int as total,
           count(*) filter (where g.steam_appid is not null)::int as with_appid,
           count(*) filter (where g.deleted)::int as deleted,
           count(*) filter (
             where g.steam_appid is not null and not g.deleted
               and (g.description is null or g.description = ''
                    or not exists (select 1 from offers o where o.game_id = g.id and o.platform_code = 'steam'))
           )::int as pending,
           count(*) filter (where exists (select 1 from offers o2 where o2.game_id = g.id))::int as with_offers
      from games g`);
  const row = r.rows[0] ?? {};
  const total = Number(row.total ?? 0);
  const withAppid = Number(row.with_appid ?? 0);
  const deleted = Number(row.deleted ?? 0);
  const pending = Number(row.pending ?? 0);
  return {
    total,
    withAppid,
    pending,
    deleted,
    withOffers: Number(row.with_offers ?? 0),
    // 已同步 = 有 appid 且不在待同步里（目录里没有 appid 的行不计入进度）
    synced: Math.max(0, withAppid - deleted - pending),
  };
}

/** 已删除（回收站）的游戏列表，按删除时间倒序。 */
export async function listDeletedGames(q, { limit = 200 } = {}) {
  const r = await q(
    `select g.id, g.steam_appid, coalesce(g.name, 'appid:' || g.steam_appid) as name, g.name_en,
            g.app_type, g.deleted_at,
            coalesce(array_agg(distinct p.name) filter (where p.name is not null), '{}') as platform_names,
            (select count(*)::int from offers o where o.game_id = g.id) as offer_count
       from games g
       left join offers o on o.game_id = g.id
       left join platforms p on p.code = o.platform_code
      where g.deleted
      group by g.id
      order by g.deleted_at desc nulls last
      limit $1`,
    [Math.min(Math.max(Number(limit) || 200, 1), 1000)],
  );
  return r.rows;
}
